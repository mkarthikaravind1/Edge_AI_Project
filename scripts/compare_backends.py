"""M2.5 / M2.6: build the backend comparison and target-vs-achieved tables from evidence/M2/*.json.

    python scripts/compare_backends.py      -> evidence/M2/comparison.md (+ .json)

Nothing is typed in by hand: every number comes from benchmark_<host>_<backend>.json and accuracy_compare.json.
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ORDER = ["pytorch_fp32", "onnx_fp32", "onnx_int8", "tflite_fp32", "tflite_fp16", "tflite_int8", "tflite_int8_full"]


def main() -> None:
    ev = ROOT / "evidence/M2"
    acc = json.loads((ev / "accuracy_compare.json").read_text())["results"] if (ev / "accuracy_compare.json").exists() else {}
    targets = json.loads((ROOT / "docs/targets.json").read_text())
    rows = []
    for f in sorted(ev.glob("benchmark_*_*.json")):
        b = json.loads(f.read_text())
        host = b["host"]
        a = acc.get(b["backend"], {})
        rows.append({
            "host": f"{host['device_type']} ({host['cpu_model'][:40]})",
            "host_tag": f.stem.split("_")[1],
            "backend": b["backend"], "size_mb": b["model_size_mb"], "threads": b["threads"],
            "infer_median_ms": b["infer"]["median_ms"], "infer_p95_ms": b["infer"]["p95_ms"],
            "total_median_ms": b["total"]["median_ms"], "fps_total": b["fps_total"],
            "mAP50_test": a.get("test_real", {}).get("mAP50"), "mAP50_95_test": a.get("test_real", {}).get("mAP50_95"),
            "mAP50_val": a.get("val_real", {}).get("mAP50"), "mAP50_95_val": a.get("val_real", {}).get("mAP50_95"),
        })
    rows.sort(key=lambda r: (r["host_tag"], ORDER.index(r["backend"]) if r["backend"] in ORDER else 99))

    md = ["# M2 comparison (generated by `scripts/compare_backends.py`)", "",
          "Batch 1, imgsz 320, 20 warm-up + 200 timed runs on real test images. Accuracy on the same real images for every backend.", "",
          "| host | backend | size MB | infer median ms | infer p95 ms | detect() median ms | FPS | mAP50 test | mAP50-95 test | mAP50 val | mAP50-95 val |",
          "|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        md.append(f"| {r['host']} | {r['backend']} | {r['size_mb']} | {r['infer_median_ms']} | {r['infer_p95_ms']} | "
                  f"{r['total_median_ms']} | {r['fps_total']} | {r['mAP50_test']} | {r['mAP50_95_test']} | "
                  f"{r['mAP50_val']} | {r['mAP50_95_val']} |")

    md += ["", "## Target vs achieved", "", "| target | INT8 model | value | achieved | met? |", "|---|---|---|---|---|"]

    def line(name: str, model: str, target: str, value, ok) -> None:
        md.append(f"| {name} | {model} | {target} | {value if value is not None else 'pending'} | "
                  f"{'pending' if ok is None else ('yes' if ok else 'NO')} |")

    # INT8 is compared with the FP32 model of the SAME runtime: identical pre/post-processing, so the only
    # difference is quantisation (PyTorch pads images differently, which would blur the comparison).
    same_runtime_fp32 = {"onnx_int8": "onnx_fp32", "tflite_int8": "tflite_fp32", "tflite_int8_full": "tflite_fp32"}
    for b in ("onnx_int8", "tflite_int8", "tflite_int8_full"):
        ref = same_runtime_fp32[b]
        fp32 = acc.get(ref, {}).get("val_real", {}).get("mAP50")
        int8 = acc.get(b, {}).get("val_real", {}).get("mAP50")
        size = acc.get(b, {}).get("size_mb")
        pi = next((r for r in rows if r["host_tag"] == "pi" and r["backend"] == b), None)
        drop = round(fp32 - int8, 4) if fp32 is not None and int8 is not None else None
        line(f"mAP@0.5 drop vs {ref} (real val)", b, f"<= {targets['int8_map50_drop_max']}", drop,
             None if drop is None else drop <= targets["int8_map50_drop_max"])
        line("model size", b, f"<= {targets['int8_size_mb_max']} MB", size,
             None if size is None else size <= targets["int8_size_mb_max"])
        line("Pi median inference", b, f"<= {targets['pi4_median_infer_ms_max']} ms (Pi 4) / {targets['pi5_median_infer_ms_max']} ms (Pi 5)",
             pi["infer_median_ms"] if pi else None, None if not pi else pi["infer_median_ms"] <= targets["pi4_median_infer_ms_max"])
    (ev / "comparison.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    (ev / "comparison.json").write_text(json.dumps(rows, indent=2))
    print("\n".join(md))


if __name__ == "__main__":
    main()
