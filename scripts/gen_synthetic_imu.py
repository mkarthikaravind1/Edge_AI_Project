"""SYNTHETIC IMU data, only for developing M4 code before real MPU6050 runs exist.

Normal: motor hum at ~25 Hz + small noise. Fault: unbalanced load (strong 1x component + harmonics)
and random taps (impulses). Real recordings in data/imu/real/ replace these for marks.

    python scripts/gen_synthetic_imu.py
"""

from __future__ import annotations

import csv
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]


def run(kind: str, seed: int, seconds: float = 30, rate: int = 200) -> np.ndarray:
    rng = np.random.default_rng(seed)
    t = np.arange(int(seconds * rate)) / rate
    f0 = rng.uniform(23, 27)
    amp = rng.uniform(0.015, 0.025)
    sig = np.zeros((len(t), 6))
    for i in range(3):
        sig[:, i] = amp * np.sin(2 * np.pi * f0 * t + rng.uniform(0, 6.3)) + rng.normal(0, 0.008, len(t))
        sig[:, 3 + i] = 0.8 * np.sin(2 * np.pi * f0 * t + rng.uniform(0, 6.3)) + rng.normal(0, 0.3, len(t))
    sig[:, 2] += 1.0                                  # gravity on z
    if kind == "fault_unbalance":
        for i in range(3):
            sig[:, i] += 4 * amp * np.sin(2 * np.pi * f0 * t) + 1.5 * amp * np.sin(2 * np.pi * 2 * f0 * t)
            sig[:, 3 + i] += 3.0 * np.sin(2 * np.pi * f0 * t)
    elif kind == "fault_tap":
        for k in rng.choice(len(t) - 20, size=int(seconds * 2), replace=False):
            decay = np.exp(-np.arange(20) / 4)
            sig[k:k + 20, :3] += rng.normal(0, 0.4, 3) * decay[:, None]
            sig[k:k + 20, 3:] += rng.normal(0, 20, 3) * decay[:, None]
    return np.column_stack([t, sig])


def main() -> None:
    out = ROOT / "data/imu/synthetic"
    out.mkdir(parents=True, exist_ok=True)
    plan = [("normal", i) for i in range(1, 9)] + [("fault_unbalance", i) for i in (1, 2)] + [("fault_tap", 1)]
    kinds = ["normal", "fault_unbalance", "fault_tap"]
    for kind, i in plan:
        data = run(kind, seed=100 * kinds.index(kind) + i)
        with open(out / f"{kind}_{i}.csv", "w", newline="") as f:
            w = csv.writer(f)
            w.writerow(["t", "ax", "ay", "az", "gx", "gy", "gz"])
            w.writerows(np.round(data, 5).tolist())
    (out / "README.md").write_text("SYNTHETIC data generated by scripts/gen_synthetic_imu.py - for code development only, "
                                   "NOT evidence. Real runs go to data/imu/real/.\n")
    print(f"wrote {len(plan)} synthetic runs to {out}")


if __name__ == "__main__":
    main()
