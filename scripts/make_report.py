"""Turn evidence/ into docs/RESULTS.md: one table per milestone with the key numbers of every file.

    python scripts/make_report.py
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
SKIP = {"host", "task", "params", "items", "real_blocks", "transforms", "videos"}


def flatten(d: Any, prefix: str = "") -> dict[str, Any]:
    out: dict[str, Any] = {}
    if isinstance(d, dict):
        for k, v in d.items():
            if k in SKIP:
                continue
            out.update(flatten(v, f"{prefix}{k}."))
    elif isinstance(d, list):
        if len(d) <= 6 and all(not isinstance(x, (dict, list)) for x in d):
            out[prefix[:-1]] = ", ".join(map(str, d))
    else:
        out[prefix[:-1]] = d
    return out


def main() -> None:
    lines = ["# Results", "", "Generated by `scripts/make_report.py` from `evidence/`. Do not edit by hand.", ""]
    for m in sorted((ROOT / "evidence").glob("M*")):
        files = sorted(m.glob("*.json"))
        if not files:
            continue
        lines += [f"## {m.name}", ""]
        for f in files:
            data = json.loads(f.read_text())
            if not isinstance(data, dict):
                continue
            host = data.get("host", {})
            where = f" — measured on **{host.get('device_type', '?')}** ({host.get('cpu_model', '?')})" if host else ""
            lines += [f"### `{f.relative_to(ROOT).as_posix()}`{where}", "", "| metric | value |", "|---|---|"]
            for k, v in list(flatten(data).items())[:40]:
                lines.append(f"| {k} | {v} |")
            pngs = sorted(m.glob(f"{f.stem}*.png"))
            for p in pngs[:3]:
                lines.append(f"\n![{p.stem}](../{p.relative_to(ROOT).as_posix()})")
            lines.append("")
    (ROOT / "docs/RESULTS.md").write_text("\n".join(lines), encoding="utf-8")
    print("wrote docs/RESULTS.md")


if __name__ == "__main__":
    main()
